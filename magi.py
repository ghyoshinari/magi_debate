def now_stamp():
    return datetime.now().strftime("%H:%M:%S")


def determine_alert_level(
    convergence_achieved: bool,
    round_num: int
) -> str:

    if convergence_achieved and round_num <= 2:
        return (
            "LEVEL 1 (LOW) - Rapid Consensus. "
            "Requires standard human homologation."
        )

    if convergence_achieved and round_num <= 5:
        return (
            "LEVEL 2 (MEDIUM) - Late Consensus/Friction. "
            "Careful review of previously contested "
            "divergence points is recommended."
        )

    return (
        "LEVEL 3 (CRITICAL) - Structural Impasse. "
        "MANDATORY LOCKOUT: Requires Dual Verification "
        "and 100% human ethical deliberation."
    )


def normalize_convergence(value):
    """
    Accepts:
    85
    85.0
    "85"
    "85.0"

    Clamps the result to the 0-100 range.
    """
    try:
        score = int(round(float(value)))
    except (TypeError, ValueError):
        return 0

    return max(0, min(100, score))


def normalize_themes(value):
    if value is None:
        return []

    if isinstance(value, list):
        return [str(item) for item in value]

    return [str(value)]

