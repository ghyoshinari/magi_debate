# 2. DATABASE MANAGEMENT (SQLITE)
# ==============================================================================

def db_connect():
    conn = sqlite3.connect(DB_NAME, timeout=30)
    conn.execute("PRAGMA busy_timeout = 30000")
    return conn


def init_db():
    conn = db_connect()

    try:
        cursor = conn.cursor()

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS Sessions (
                session_id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp TEXT,
                user_prompt TEXT,
                final_status TEXT,
                alert_level TEXT,
                final_synthesis TEXT
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS Round_Deliberations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                session_id INTEGER,
                round_num INTEGER,
                agent_name TEXT,
                response TEXT,
                FOREIGN KEY(session_id)
                    REFERENCES Sessions(session_id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS Coordinator_Analyses (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                session_id INTEGER,
                round_num INTEGER,
                themes_json TEXT,
                convergence_score INTEGER,
                round_summary TEXT,
                FOREIGN KEY(session_id)
                    REFERENCES Sessions(session_id)
            )
        """)

        # Backward compatibility for databases generated by prior versions
        cursor.execute("PRAGMA table_info(Coordinator_Analyses)")
        columns = {row[1] for row in cursor.fetchall()}

        if "round_summary" not in columns:
            cursor.execute(
                "ALTER TABLE Coordinator_Analyses "
                "ADD COLUMN round_summary TEXT"
            )

        conn.commit()

    finally:
        conn.close()


def log_to_db(query: str, params: tuple):
    conn = db_connect()

    try:
        cursor = conn.cursor()
        cursor.execute(query, params)

        last_id = cursor.lastrowid

        conn.commit()

        return last_id

    finally:
        conn.close()

